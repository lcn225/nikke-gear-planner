# -*- coding: utf-8 -*-
"""
外部词条名 → 标准名的翻译层。

**本文件是全仓库唯一允许出现非标准词条名的地方。**
除此之外（config.py、engine/、models/、以及所有自有数据文件）只使用
TIER_VALUE_MATRIX 的 9 个标准名，即游戏内原文：
    攻击力增加 / 优越代码伤害增加 / 最大装弹数增加 / 蓄力速度增加 / 暴击率增加
    暴击伤害增加 / 防御力增加 / 命中率增加 / 蓄力伤害增加

为什么必须有这一层：上游推荐词的原文就是「蓄速」「爆伤」「优越伤害」这类简称，
改不了也绕不开。做法是在**整理快照时**翻译，不让旧名进引擎。

回归防线：test/test_no_legacy_names.py 会扫描全仓，别名表以外出现旧名即失败。
新增外部数据源时，把它的写法加进下面的表，不要在下游就地改名。
"""

from config import BUFF_NAMES, EMPTY_BUFF_NAME, TIER_VALUE_MATRIX

# ────────────────────────────────────────────────────────────
# 自动推导：标准名去掉「增加」后缀
#
# 9 个标准名全部以「增加」结尾，去掉后互不重复，可以安全自动生成：
#     攻击力增加 → 攻击力      最大装弹数增加 → 最大装弹数
#     优越代码伤害增加 → 优越代码伤害        蓄力速度增加 → 蓄力速度
#
# 注意这里**不**再往前剥「伤害」二字：那会让「蓄力伤害增加」和
# 「蓄力速度增加」同时产出「蓄力」，撞成一个歧义键。
# 这类需要额外剥一层的前缀（优越代码）走下面的显式表。
# ────────────────────────────────────────────────────────────

def _auto_derived() -> dict[str, str]:
    table = {}
    for std in BUFF_NAMES:
        base = std[:-2] if std.endswith("增加") else std
        if base in table and table[base] != std:
            raise ValueError(f"自动推导的别名 '{base}' 撞车: {table[base]} 与 {std}")
        table[base] = std
    return table


# ────────────────────────────────────────────────────────────
# 显式别名：无法从标准名推导出来的写法
#   来源 = 历史 roster 短名 + 上游推荐表的简称 + 攻略贴写法
# ────────────────────────────────────────────────────────────

IRREGULAR_ALIASES: dict[str, str] = {
    # 攻击力增加
    "攻刃": "攻击力增加",
    "攻击": "攻击力增加",
    # 优越代码伤害增加（注意是 6 个字，不是「优越代码增加」）
    "优越": "优越代码伤害增加",
    "优越代码": "优越代码伤害增加",
    "优越伤害": "优越代码伤害增加",
    # 最大装弹数增加
    "最大装弹量": "最大装弹数增加",
    "最大装弹": "最大装弹数增加",
    "装弹量": "最大装弹数增加",
    "装弹数": "最大装弹数增加",
    "装弹": "最大装弹数增加",
    # 蓄力速度增加
    "蓄速": "蓄力速度增加",
    # 暴击率增加
    "暴率": "暴击率增加",
    # 裸「暴击」= 暴击率的简写。这不是猜：全量 804 条文本里裸「暴击」出现 280 次，
    # 其中 279 次与「爆伤/暴伤」成对（社区标准简写对 暴击/爆伤），
    # 单独出现仅 1 次（伊芙「暴击*2」）。而显式写「暴击率」只有 18 次。
    "暴击": "暴击率增加",
    # 暴击伤害增加
    "爆伤": "暴击伤害增加",
    "暴伤": "暴击伤害增加",
    # 防御力增加
    "防御": "防御力增加",
    # 命中率增加
    "命中": "命中率增加",
    # 上游攻略作者把「蓄力伤害」写成「充能伤害」（仅 1 处：娜由塔/PVE/optional）。
    # 用户判定为笔误，非独立词条 —— 9 个标准词条里没有「充能伤害」。
    "充能伤害": "蓄力伤害增加",
}


# ────────────────────────────────────────────────────────────
# 一对多：一个写法同时指代多个词条。
# 只放确实如此的压缩写法，不要因为「不确定指哪个」就塞进来 ——
# 那会把「不知道」变成「两个都要」，静默改变目标集合。
# ────────────────────────────────────────────────────────────

MULTI_ALIASES: dict[str, list[str]] = {
    # 暴击率 + 暴击伤害 的合写（上游语料: 蕾贝儿/PVP/optional）
    "双爆": ["暴击率增加", "暴击伤害增加"],
    # 攻击力 + 优越代码 的合写（上游语料: 拉普拉斯：究极英雄/PVP/optional）
    "攻优": ["攻击力增加", "优越代码伤害增加"],
}


def _build_table() -> dict[str, str]:
    table = _auto_derived()
    for alias, std in IRREGULAR_ALIASES.items():
        if alias in TIER_VALUE_MATRIX:
            raise ValueError(f"别名 '{alias}' 与标准名冲突，不该出现在别名表里")
        if alias in table and table[alias] != std:
            raise ValueError(f"别名 '{alias}' 撞车: {table[alias]} 与 {std}")
        table[alias] = std
    return table


ALIAS_TABLE: dict[str, str] = _build_table()


def to_standard(raw: str) -> str | None:
    """
    把外部写法翻成**单个**标准名。

    标准名原样返回（幂等）；空占位符「未获得效果」原样返回；
    认不出来返回 None —— 由调用方记进 review 交人工裁决，不在这里猜。

    一对多的压缩写法（双爆/攻优）请用 expand()，本函数只返回 None。
    """
    if not raw:
        return raw
    raw = raw.strip()
    if raw in TIER_VALUE_MATRIX or raw == EMPTY_BUFF_NAME:
        return raw
    return ALIAS_TABLE.get(raw)


def expand(raw: str) -> list[str] | None:
    """
    把外部写法翻成标准名**列表**（处理一对多）。

    单值写法返回长度 1 的列表；一对多写法（双爆/攻优）返回多个；
    认不出来返回 None。
    """
    if not raw:
        return None
    raw = raw.strip()
    if raw in MULTI_ALIASES:
        return list(MULTI_ALIASES[raw])
    one = to_standard(raw)
    return [one] if one else None


# ═══════════════════════════════════════════════════════════════
# 语料噪声词表
#
# 上面是「写法 → 标准名」的翻译；这里是「什么不是词条名」的判断。
# 两者都是**外部语料知识**，所以放同一个文件：全仓库只有这一处知道
# 上游推荐词的原文长什么样。快照生成侧的解析与覆盖率验证脚本都从这里取，
# 不各留一份 —— 复制两份必然漂移，而这个项目已经在命名分裂上吃过三次亏。
# （那些脚本不入库，但这一层要留下：引擎读快照时仍靠它兜住历史别名。）
# ═══════════════════════════════════════════════════════════════

import re

# 数量语法：*4 / ×3 / 1-2 / 1~4 / 2-3
NUMBER_NOISE = re.compile(
    r"[（(][^）)]*[）)]"       # 整个括号块（内含「至少2条」「2条以上」等）
    r"|[*×xX]\s*\d+"          # *4 / ×3
    r"|\d+\s*[-~～]\s*\d+"    # 1-2 / 1~4
    r"|\d+"                   # 裸数字
)

# 语气词/条件词：上游攻略作者的文字，不是词条名。
# 每加一个都要有理由；不要为了让某个检查通过而往里塞东西。
PROSE_NOISE = [
    "以上", "至少", "条", "个", "件", "选", "可", "更佳", "尽量", "优先",
    "任意", "随意", "随便", "无需", "不用", "无要求", "要求", "跟随",
    "洗满", "刷满", "刷取", "洗出", "注意", "不要", "禁止", "即可", "都行",
    "数值", "的词条", "词条", "属性", "多了", "没用", "浪费",
    "对", "很", "高", "低", "和", "或", "与", "及", "等",
    # 数量约束语（不是词条名）：「（越多越好）」「爆伤越多越好」
    "越多越好", "凑够", "养成", "更推荐", "推荐", "方案", "根据需求",
    # 否定语。它们出现意味着「这个词条是反目标」——
    # 解析器必须据此把整条送去人工裁决，而不是朴素地解析成目标。
    "不需要", "不推荐",
    # 哨兵值里的 pve/pvp（大小写都见）
    "pve", "pvp", "PVE", "PVP",
]

# 标点与空白。裸 * 也算（「蓄速*越多越好」里 * 后面不是数字）
PUNCT_NOISE = re.compile(r"[\s,，、/／|+＋\-—~～.。:：;；!！?？*\"'“”‘’\[\]【】<>《》①②③④⑤]+")

# 整体就是「没有要求」的哨兵值：不产生任何目标词条，是合法输入
SENTINEL_WHOLE = ["无需", "随意刷取", "随便", "无要求", "跟随pve", "跟随pvp",
                  "跟随PVE", "跟随PVP", "跟随PVE即可", "跟随PVP即可"]

# 明确表达「不要某个词条」的否定语。命中即不等于「没要求」，
# 而是「有反面要求」—— 不能当空处理，也不能当正向目标处理。
NEGATION_WORDS = ["不要", "禁止", "不推荐", "不需要"]


def strip_noise(text: str) -> str:
    """
    消掉已知的词条写法 / 数量语法 / 噪声词，返回残渣。

    残渣非空说明这段文本里有别名表和噪声词表都解释不了的东西 ——
    调用方应把它记进 review 交人工裁决，而不是丢掉。
    """
    s = text
    # 1. 括号块先整块消掉（里面常含空格，不能按空白切分）
    s = NUMBER_NOISE.sub(" ", s)
    # 2. 已知词条写法：长的先消，避免「最大装弹数」被「最大装弹」截断。
    #    一对多的压缩写法（双爆/攻优）也要消，否则会留下半截。
    keys = list(ALIAS_TABLE) + list(MULTI_ALIASES)
    for key in sorted(keys, key=len, reverse=True):
        s = s.replace(key, " ")
    # 3. 语气词
    for w in sorted(PROSE_NOISE, key=len, reverse=True):
        s = s.replace(w, " ")
    # 4. 标点
    s = PUNCT_NOISE.sub(" ", s)
    return s.strip()
