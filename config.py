def get_tier_value(buff_name: str, tier: int) -> float:
    """
    获取指定词条在指定档位的百分比值（1-indexed tier, 1-15）。

    词条名不在表里时抛错而不是返回 0.0 —— 静默返回 0 会让「名字写错」伪装成
    「该词条收益为零」，这正是旧 legacy/excel_to_my_roster.py 把 17 条防御力词条
    兜底成 tier=1 的原因（见 [[nikke-progress-2026-09-25]]）。
    """
    if buff_name not in TIER_VALUE_MATRIX:
        raise KeyError(f"未知词条 '{buff_name}'，不在 TIER_VALUE_MATRIX 中")
    if not 1 <= tier <= 15:
        raise ValueError(f"档位越界: {buff_name} tier={tier}（应为 1-15）")
    return TIER_VALUE_MATRIX[buff_name][tier - 1]


def get_tier11_value(buff_name: str) -> float:
    """获取指定词条在 Tier 11 的百分比值（作为高档位参考锚点）"""
    return get_tier_value(buff_name, 11)


def value_to_tier(buff_name: str, value_pct: float) -> int:
    """
    由百分比数值反查档位（1-indexed）。

    上游 input/cn_collect.json 只给数值不给档位，数值精确落在 15 档上
    （input/数据说明.md 第六节已核对 0 条越档），所以这里是精确匹配。
    差超过 0.005 说明数值不在合法档位上，抛错而不是取最近档 —— 静默取最近档
    会把 OCR 错误当成合法数据。
    """
    if buff_name not in TIER_VALUE_MATRIX:
        raise KeyError(f"未知词条 '{buff_name}'，不在 TIER_VALUE_MATRIX 中")
    ladder = TIER_VALUE_MATRIX[buff_name]
    best_i, best_diff = 0, abs(value_pct - ladder[0])
    for i, v in enumerate(ladder):
        d = abs(value_pct - v)
        if d < best_diff:
            best_i, best_diff = i, d
    if best_diff > 0.005:
        raise ValueError(
            f"'{buff_name}' 的数值 {value_pct}% 不在合法档位上"
            f"（最近的 Tier {best_i + 1} = {ladder[best_i]}%，差 {best_diff:.4f}）"
        )
    return best_i + 1

