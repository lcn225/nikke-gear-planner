# 是在编。所以只暴露一个参数 q，含义是一句人话：
#
#     q = 每差半档，培养优先级打几折
#
# 权重 w(tier) = q^(2×tier)，即 tier 每降 0.5 档乘一次 q。
# 取 q=0.8 得到的量表（T1 归一为 0.64）：
#     T0 ×1.000   T0.5 ×0.800   T1 ×0.640
#     T1.5 ×0.512  T2 ×0.410    T3 ×0.262
#
# ⚠️ 这组数不是推导出来的，是**选**出来的。它的合理性靠敏感性检验支撑：
#    换几个 q 跑一遍，看天梯前 N 名变不变。结论稳健 → 具体取值不重要。
# ═══════════════════════════════════════════════════════════════

TIER_WEIGHT_Q = 0.8

# 仓管：攻略标注为「用不上」的角色。权重恒为 0 —— 这不是系数，
# 是事实：不会上场的角色，投进去的收益就是 0。
TIER_CG = "cg"
CG_WEIGHT = 0.0


def tier_rank(tier) -> float:
    """
    档位的排序键（越小越靠前）。用于角色榜「档位优先」的分组。

    与 tier_weight 分开：权重是**倍率**（用于折算 ROI），rank 是**次序**
    （用于分组）。档位表若将来加档，两处都要动，所以放一起。
    """
    if tier is None or tier == "":
        return 98.0
    if str(tier) == TIER_CG:
        return 99.0
    try:
        return float(tier)
    except (TypeError, ValueError):
        return 98.0


def tier_weight(tier, q: float = None) -> float:
    """
    培养优先级权重。tier 取上游的 "0"/"0.5"/…/"3"/"cg"。

    未知或缺失的档位返回 1.0（不折算），而不是猜一个值 ——
    猜低了会把角色默默压下去，猜高了会默默抬上来，两种都比不折算更糟。
    """
    if tier is None or tier == "":
        return 1.0
    if str(tier) == TIER_CG:
        return CG_WEIGHT
    try:
        t = float(tier)
    except (TypeError, ValueError):
        return 1.0
    return (TIER_WEIGHT_Q if q is None else q) ** (2.0 * t)
